-- 기업 요금제(company_subscriptions)를 기업 Pro 이용 기간(company_plan_periods) 한 테이블로 합친다.
-- 체험(TRIAL, 14일 0원)과 결제한 이용권(PRO_1M 30일 49,000원, PRO_3M 90일 129,000원)이 한 줄씩 쌓인다.
-- 자동 실행되지 않는다. DDL_AUTO=update여도 데이터 이동과 테이블 삭제는 하지 않으므로 서버 DB에 직접 적용한다.
-- 다시 실행해도 오류가 나지 않는다.
BEGIN;

CREATE TABLE IF NOT EXISTS company_plan_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id UUID NOT NULL REFERENCES users (id),
    product VARCHAR(20) NOT NULL,
    days INT NOT NULL,
    amount_krw INT NOT NULL,
    pg_transaction_id VARCHAR(200) UNIQUE,
    status VARCHAR(20) NOT NULL,
    starts_at TIMESTAMP NULL,
    ends_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL
);

-- 기존 체험 기록을 TRIAL 줄로 옮기고 company_subscriptions를 지운다.
-- 머지된 코드에서 company_subscriptions에 쓰인 값은 체험(trial_ends_at)뿐이다. 유료 기간(expires_at)은 쓰인 적이 없다.
DO $$
BEGIN
    IF to_regclass('public.company_subscriptions') IS NOT NULL THEN
        INSERT INTO company_plan_periods (company_id, product, days, amount_krw, status, starts_at, ends_at, created_at)
        SELECT s.company_id, 'TRIAL', 14, 0, 'PAID', s.trial_ends_at - INTERVAL '14 days', s.trial_ends_at, s.trial_ends_at - INTERVAL '14 days'
        FROM company_subscriptions s
        WHERE s.trial_ends_at IS NOT NULL
          AND NOT EXISTS (SELECT 1 FROM company_plan_periods p WHERE p.company_id = s.company_id AND p.product = 'TRIAL');
        DROP TABLE company_subscriptions;
    END IF;
END $$;

COMMIT;
