-- 기업 Pro 이용권 결제(1개월 30일 49,000원, 3개월 90일 129,000원).
-- 자동 실행되지 않는다. DDL_AUTO가 none인 DB(배포 서버 등)에 직접 적용한다. 다시 실행해도 오류가 나지 않는다.
BEGIN;

CREATE TABLE IF NOT EXISTS company_pro_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id UUID NOT NULL REFERENCES users (id),
    product VARCHAR(20) NOT NULL,
    days INT NOT NULL,
    amount_krw INT NOT NULL,
    pg_transaction_id VARCHAR(200) UNIQUE,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_company_pro_payments_company ON company_pro_payments (company_id, created_at DESC);

COMMIT;
