-- 기존 ERD의 badge / user_badge 테이블을 기준으로 한 PostgreSQL 마이그레이션.
-- 운영 반영 전 badge.code 중복 여부를 확인한다.
-- 재실행 시 기존 status(특히 GRACE)와 기록을 유지하고 누락된 구조만 추가한다.
BEGIN;

CREATE UNIQUE INDEX IF NOT EXISTS uq_badge_code ON badge (code);

INSERT INTO badge (id, type, code, name)
SELECT COALESCE((SELECT MAX(id) FROM badge), 0) + 1,
       'REVIEWER', 'REVIEWER', '리뷰어'
WHERE NOT EXISTS (SELECT 1 FROM badge WHERE code = 'REVIEWER');

INSERT INTO badge (id, type, code, name)
SELECT COALESCE((SELECT MAX(id) FROM badge), 0) + 1,
       'REVIEWER', 'EXCELLENT_REVIEWER', '우수 리뷰어'
WHERE NOT EXISTS (SELECT 1 FROM badge WHERE code = 'EXCELLENT_REVIEWER');

ALTER TABLE user_badge ADD COLUMN IF NOT EXISTS status VARCHAR(20);
ALTER TABLE user_badge ADD COLUMN IF NOT EXISTS grace_until TIMESTAMP NULL;

UPDATE user_badge
SET status = CASE
    WHEN is_eligible = true AND (expires_at IS NULL OR expires_at > CURRENT_TIMESTAMP)
        THEN 'ACTIVE'
    ELSE 'EXPIRED'
END
WHERE status IS NULL;

UPDATE user_badge
SET continuous_since = acquired_at
WHERE status = 'ACTIVE' AND continuous_since IS NULL;

ALTER TABLE user_badge ALTER COLUMN status SET NOT NULL;
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'user_badge'::regclass AND conname = 'ck_user_badge_status'
    ) THEN
        ALTER TABLE user_badge ADD CONSTRAINT ck_user_badge_status
            CHECK (status IN ('ACTIVE', 'GRACE', 'EXPIRED'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS user_badge_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(id),
    badge_id INT NOT NULL REFERENCES badge(id),
    active_from TIMESTAMP NOT NULL,
    active_until TIMESTAMP NOT NULL,
    CONSTRAINT ck_user_badge_history_period CHECK (active_from <= active_until)
);

CREATE INDEX IF NOT EXISTS ix_user_badge_history_user ON user_badge_history(user_id, active_until DESC);
CREATE INDEX IF NOT EXISTS ix_user_badge_active ON user_badge(badge_id, user_id)
    WHERE status = 'ACTIVE';

COMMIT;
