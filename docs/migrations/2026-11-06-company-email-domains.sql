-- 기업 이메일 인증에 쓸 수 있는 도메인 목록.
-- 이 목록의 도메인으로 인증을 마친 회원은 users.role이 COMPANY가 된다.
-- 자동 실행되지 않는다. DDL_AUTO가 none인 DB(배포 서버 등)에 직접 적용한다.
BEGIN;

CREATE TABLE IF NOT EXISTS company_email_domains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_company_email_domains_domain UNIQUE (domain)
);

-- '@' 없이 소문자로 넣는다.
INSERT INTO company_email_domains (domain, created_at) VALUES
    ('newlecture.com', CURRENT_TIMESTAMP),
    ('ssamsung.com', CURRENT_TIMESTAMP),
    ('rg.com', CURRENT_TIMESTAMP)
ON CONFLICT (domain) DO NOTHING;

COMMIT;
