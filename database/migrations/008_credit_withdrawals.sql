-- 크레딧 환전 테이블과 내역의 환전 FK 컬럼을 추가한다.
BEGIN;

CREATE TABLE IF NOT EXISTS credit_withdrawals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    user_id uuid NOT NULL REFERENCES users(id),
    credits integer NOT NULL,
    amount_krw integer NOT NULL,
    fee_krw integer NOT NULL,
    bank_name character varying(30) NOT NULL,
    account_number character varying(30) NOT NULL,
    account_holder character varying(50) NOT NULL
);

ALTER TABLE credit_transactions
    ADD COLUMN IF NOT EXISTS credit_withdrawal_id bigint;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_credit_transactions_credit_withdrawal'
    ) THEN
        ALTER TABLE credit_transactions
            ADD CONSTRAINT fk_credit_transactions_credit_withdrawal
            FOREIGN KEY (credit_withdrawal_id) REFERENCES credit_withdrawals(id);
    END IF;
END $$;

COMMIT;
